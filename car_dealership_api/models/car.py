class Car:
    def __init__(self, car_id, make, model, year, fuel_type, mileage, price, status):
        self.car_id = car_id
        self.make = make
        self.model = model
        self.year = year
        self.fuel_type = fuel_type
        self.mileage = mileage
        self.price = price
        self.status = status
